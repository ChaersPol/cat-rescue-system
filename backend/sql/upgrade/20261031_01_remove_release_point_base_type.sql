-- ============================================================
-- 变更：基地类型只保留「饲养基地」「医疗基地」，移除「放归点位」
-- 影响表：sys_dict_data（删字典项）、cat_base（类型迁移）
-- 可回滚：是（见文末）
-- 作者/日期：workbuddy / 2026-10-31
-- 说明：
--   1) 原字典 cat_base_type：1=饲养基地、2=医疗基地、3=放归点位。
--      业务确认放归点位不属于「基地」，需移除该类型。
--   2) 仍在使用该类型的基地统一迁移为「饲养基地」，不删除记录，
--      避免破坏 cat_profile.base_id / cat_flow.to_base_id 等历史关联。
--      其中「河湾放归点位」同步改名为「河湾救助基地」，与类型语义保持一致。
--   3) TNR 放归记录里的「放归点位」（cat_release.release_point）是独立字段，
--      与本字典无关，不做改动。
--   4) 本脚本幂等，可重复执行。
-- ============================================================

USE cat_rescue;

-- ------------------------------------------------------------
-- 1. 迁移仍在用「放归点位」的基地到「饲养基地」
-- ------------------------------------------------------------
-- 1.1 指定改名的那条（原名与类型都在时才动，避免误伤）
UPDATE `cat_base`
   SET `base_type` = '1',
       `base_name` = '河湾救助基地'
 WHERE `base_type` = '3'
   AND `base_name` = '河湾放归点位';

-- 1.2 兜底：其余残留在「放归点位」的基地一律转为饲养基地
UPDATE `cat_base` SET `base_type` = '1' WHERE `base_type` = '3';

-- ------------------------------------------------------------
-- 2. 删除「放归点位」字典项
-- ------------------------------------------------------------
DELETE FROM `sys_dict_data`
 WHERE `dict_type` = 'cat_base_type'
   AND `dict_value` = '3';

-- ------------------------------------------------------------
-- 3. 更正字段注释（原注释仍写着「3放归点位」）
-- ------------------------------------------------------------
ALTER TABLE `cat_base`
  MODIFY COLUMN `base_type` char(1) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci
  DEFAULT '1' COMMENT '基地类型（1饲养基地 2医疗基地）';

